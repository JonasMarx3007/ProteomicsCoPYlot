"""Add PyPI artifact hashes to the existing runtime pins without resolving versions.

Run after reviewing changes to backend/requirements-runtime.lock. Include all
published artifacts for each version so the hash lock works across platforms.
"""
from __future__ import annotations

import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PINS = ROOT / "backend/requirements-runtime.lock"
HASHED = ROOT / "backend/requirements-runtime-hashed.lock"


def read_pins(text: str) -> list[tuple[str, str]]:
    pins = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z0-9_.-]+)==([^\s;]+)", line)
        if not match:
            raise ValueError(f"Expected an exact package pin: {line}")
        pins.append(match.groups())
    if not pins:
        raise ValueError("Runtime dependency lock is empty.")
    return pins


def render(pins: list[tuple[str, str]], releases: dict) -> str:
    lines = [
        "# Generated by tools/hash_runtime_requirements.py; do not edit by hand.",
        "# Exact versions come from requirements-runtime.lock; no version resolution.",
        "# SHA-256 hashes cover published PyPI wheels and source archives for each pin.",
        "# Conda-installed packages on Intel macOS are outside pip hash verification.",
        "# Install with: python -m pip install --require-hashes -r backend/requirements-runtime-hashed.lock",
        "",
    ]
    for name, version in pins:
        release = releases[name]
        if release["info"]["version"] != version:
            raise ValueError(f"Unexpected release metadata for {name}=={version}")
        hashes = sorted({f["digests"]["sha256"] for f in release["urls"] if not f["yanked"]})
        if not hashes or any(not re.fullmatch(r"[a-f0-9]{64}", digest) for digest in hashes):
            raise ValueError(f"No valid non-yanked artifact hashes for {name}=={version}")
        lines.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            suffix = " \\" if index < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{suffix}")
    return "\n".join(lines) + "\n"


def main() -> None:
    pins = read_pins(PINS.read_text(encoding="utf-8"))
    releases = {}
    for name, version in pins:
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
            releases[name] = json.load(response)
    content = render(pins, releases)
    HASHED.write_text(content, encoding="utf-8", newline="\n")
    print(f"Recorded artifact hashes for {len(pins)} unchanged versions.")


if __name__ == "__main__":
    main()
