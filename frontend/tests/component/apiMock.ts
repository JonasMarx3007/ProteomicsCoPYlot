/**
 * Every async function in src/lib/api is replaced by a mock that never settles,
 * and `fetch` never answers, so a component can be mounted without a backend.
 * A test then resolves only the calls it is about:
 *
 *   vi.mock("../../src/lib/api", async (original) => (await import("./apiMock")).mockApiModule(original));
 *   vi.mocked(api.getStatisticalOptions).mockResolvedValue(options);
 */
import { vi } from "vitest";
// Type-only: this module is loaded by the mock factory of src/lib/api itself.
import type * as Api from "../../src/lib/api";

const pending = () => new Promise<never>(() => {});

export async function mockApiModule(importOriginal: () => Promise<Record<string, unknown>>) {
  const actual = await importOriginal();
  return Object.fromEntries(
    Object.entries(actual).map(([name, value]) => [
      name,
      typeof value === "function" && value.constructor.name === "AsyncFunction" ? vi.fn(pending) : value,
    ])
  );
}

export function silenceNetwork() {
  vi.stubGlobal("fetch", vi.fn(pending));
}

/** A project with protein and phospho data loaded, as the app reports it. */
export const DATASETS = {
  activePackage: "Data",
  availablePackages: ["Data"],
  activeMetadataProfile: "Metadata",
  availableMetadataProfiles: ["Metadata"],
  autoGeneratedMetadataProfiles: [],
  protein: { filename: "protein.tsv", rows: 10, columns: 6 },
  phospho: { filename: "phospho.tsv", rows: 10, columns: 6 },
  phosprot: null,
  peptide: null,
} as unknown as Awaited<ReturnType<typeof Api.getCurrentDatasets>>;

/** Serve `DATASETS` to the pages that look up what is loaded before drawing. */
export function serveDatasets(api: typeof Api) {
  vi.mocked(api.resetBrowserSessionState).mockResolvedValue(undefined);
  vi.mocked(api.getCurrentDatasets).mockResolvedValue(DATASETS);
}
