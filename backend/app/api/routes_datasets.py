router = APIRouter(prefix="/api/datasets", tags=["datasets"])
TRUTHY_VALUES = {"1", "true", "yes", "on"}


def _viewer_mode_enabled() -> bool:
    return str(os.getenv("COPYLOT_VIEWER_MODE", "")).strip().lower() in TRUTHY_VALUES


def _include_empty_packages() -> bool:
    if not _viewer_mode_enabled():
        return True
    # In viewer mode we always hide empty packages (for example the implicit
    # session-default "Data" package) so only configured dataset packages are shown.
    return False


def _peptide_upload_dir() -> Path:
    return private_temp_dir("peptide_uploads")


def _table_upload_dir() -> Path:
    return private_temp_dir("table_uploads")


def _table_preview_response(stored) -> DatasetPreviewResponse:
    df = stored.frame
    return DatasetPreviewResponse(
        filename=stored.filename,
        kind=stored.kind,
        format=stored.filename.split(".")[-1].lower(),
        rows=len(df),
        columns=len(df.columns),
        columnNames=[str(c) for c in df.columns],
        preview=df.head(20).replace({float("nan"): None}).to_dict(orient="records"),
        suggestedIsLog2Transformed=getattr(
            stored, "suggested_is_log2_transformed", None
        ),
        sourcePath=getattr(stored, "source_path", None),
    )


def _peptide_response(stored) -> PeptidePathResponse:
    return PeptidePathResponse(
        filename=stored.filename,
        kind="peptide",
        format="path",
        path=stored.path,
        rows=0,
        columns=0,
        columnNames=[],
        preview=[],
    )


def _resolve_target_package(raw_package_name: str | None) -> str:
    text = str(raw_package_name or "").strip()
    if not text:
        return get_active_package()
    return set_active_package(text)


def _read_table_from_local_path(path_text: str):
    candidate = Path(path_text.strip()).expanduser()
    if not candidate.exists() or not candidate.is_file():
        raise FileNotFoundError(f"File not found: {candidate}")
    with candidate.open("rb") as handle:
        return candidate, read_dataframe(candidate.name, handle)


def _current_datasets_response() -> CurrentDatasetsResponse:
    current = get_all_current_datasets()

    protein = current["protein"]
    phospho = current["phospho"]
    phosprot = current["phosprot"]
    peptide = current["peptide"]

    return CurrentDatasetsResponse(
        activePackage=get_active_package(),
        availablePackages=list_packages(include_empty=_include_empty_packages()),
        activeMetadataProfile=get_active_metadata_profile(),
        availableMetadataProfiles=list_metadata_profiles(),
        autoGeneratedMetadataProfiles=list_auto_generated_profiles(),
        protein=_table_preview_response(protein) if protein else None,
        phospho=_table_preview_response(phospho) if phospho else None,
        phosprot=_table_preview_response(phosprot) if phosprot else None,
        peptide=_peptide_response(peptide) if peptide else None,
    )


def _ensure_profile_annotation_for_kind(
    *,
    kind: Literal["protein", "phospho"],
    profile_name: str,
    source_profile_name: str | None,
) -> None:
    current_dataset = get_current_dataset(kind)
    if current_dataset is None or not hasattr(current_dataset, "frame"):
        return

    uploaded_metadata = get_uploaded_metadata(kind, profile_name=profile_name)
    metadata_frame = (
        uploaded_metadata.frame
        if uploaded_metadata is not None and not uploaded_metadata.frame.empty
        else None
    )
    if metadata_frame is None:
        source_profiles = get_auto_generated_profile_sources(profile_name)
        if source_profiles:
            source_frames: list[pd.DataFrame] = []
            for source_name in source_profiles:
                source_uploaded = get_uploaded_metadata(kind, profile_name=source_name)
                source_frame = (
                    source_uploaded.frame
                    if source_uploaded is not None and not source_uploaded.frame.empty
                    else None
                )
                if source_frame is None:
                    source_annotation = get_annotation(kind, metadata_profile_name=source_name)
                    if source_annotation is not None and not source_annotation.metadata.empty:
                        source_frame = source_annotation.metadata
                if source_frame is None:
                    source_frames = []
                    break
                source_frames.append(source_frame)

            if len(source_frames) >= 2:
                combined = build_combined_metadata_frame(*source_frames)
                if not combined.empty:
                    metadata_frame = combined

    if metadata_frame is None or metadata_frame.empty:
        raise ValueError(
            f"Mixed metadata profile '{profile_name}' has no generated rows for {kind}. "
            "Generate all source metadata profiles first."
        )

    source_annotation = (
        get_annotation(kind, metadata_profile_name=source_profile_name)
        if source_profile_name
        else None
    )
    target_annotation = get_annotation(kind, metadata_profile_name=profile_name)
    reference_annotation = source_annotation or target_annotation

    is_log2_transformed = (
        None
        if reference_annotation is None
        or getattr(reference_annotation, "log2_auto_detected", False)
        else reference_annotation.is_log2_transformed
    )
    filter_config = (
        reference_annotation.filter_config
        if reference_annotation is not None
        else AnnotationFilterConfig()
    )

    computed = compute_annotation_from_metadata(
        data=current_dataset.frame,
        metadata=metadata_frame,
        is_log2_transformed=is_log2_transformed,
        min_present=filter_config.minPresent,
        filter_mode=filter_config.mode,
        filter_method=filter_config.method,
        min_percentage=filter_config.minPercentage,
        normalization=filter_config.normalization,
    )
    save_annotation(
        kind=kind,
        source_data=current_dataset.frame,
        metadata=computed.metadata,
        log2_data=computed.log2_data,
        filtered_data=computed.filtered_data,
        is_log2_transformed=computed.is_log2_transformed,
        metadata_source="uploaded",
        filter_config=filter_config,
        auto_detected=computed.auto_detected,
        warnings=computed.warnings,
        log2_auto_detected=computed.log2_auto_detected,
        metadata_profile_name=profile_name,
    )


def _ensure_selected_profile_annotations(
    profile_name: str,
    *,
    source_profile_name: str | None,
) -> None:
    _ensure_profile_annotation_for_kind(
        kind="protein",
        profile_name=profile_name,
        source_profile_name=source_profile_name,
    )
    _ensure_profile_annotation_for_kind(
        kind="phospho",
        profile_name=profile_name,
        source_profile_name=source_profile_name,
    )


@router.post("/upload", response_model=DatasetPreviewResponse)
def upload_dataset(
    file: UploadFile = File(...),
    # AnnotationKind is exactly this set; spelling it out again lets the two drift.
    kind: AnnotationKind = Form(...),
    package_name: str | None = Form(default=None, alias="packageName"),
    source_path: str | None = Form(default=None, alias="sourcePath"),
) -> DatasetPreviewResponse:
    if not file.filename:
        raise HTTPException(status_code=400, detail="Missing filename")
    try:
        ensure_upload_size(file, label="Dataset")
    except ValueError as e:
        raise HTTPException(status_code=413, detail=str(e)) from e

    normalized_source_path = str(source_path or "").strip() or None
    safe_name = Path(file.filename).name

    try:
        _ = get_extension(file.filename)
        if normalized_source_path:
            df = read_dataframe(file.filename, file.file)
        else:
            target = _table_upload_dir() / f"{uuid4().hex}_{safe_name}"
            with open_private(target, "wb") as handle:
                shutil.copyfileobj(file.file, handle)
            with target.open("rb") as handle:
                df = read_dataframe(safe_name, handle)
            normalized_source_path = str(target.resolve())
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e)) from e
    except OSError as e:
        LOGGER.exception("Failed to store uploaded file")
        raise HTTPException(status_code=500, detail="Failed to store uploaded file.") from e
    except Exception as e:
        LOGGER.exception("Failed to parse uploaded dataset")
        raise HTTPException(status_code=400, detail="Failed to parse uploaded dataset.") from e

    _resolve_target_package(package_name)

    # Re-uploading a dataset invalidates existing annotation state for that level.
    clear_annotation(kind, clear_all_profiles=True)

    stored = save_table_dataset(file.filename, kind, df, source_path=normalized_source_path)
    if kind in ("protein", "phospho"):
        clear_uploaded_metadata(kind, clear_all_profiles=True)
    return _table_preview_response(stored)


@router.post("/table-path", response_model=DatasetPreviewResponse)
def set_table_path(payload: TableDatasetPathRequest) -> DatasetPreviewResponse:
    path_text = payload.path.strip()
    if not path_text:
        raise HTTPException(status_code=400, detail="Path must not be empty")

    try:
        candidate, df = _read_table_from_local_path(path_text)
    except FileNotFoundError as e:
        raise HTTPException(status_code=400, detail=str(e)) from e
    except ValueError as e:
        raise HTTPException(status_code=400, detail=str(e)) from e
    except Exception as e:
        LOGGER.exception("Failed to parse dataset from local path")
        raise HTTPException(status_code=400, detail="Failed to parse dataset file.") from e

    _resolve_target_package(payload.packageName)

    clear_annotation(payload.kind, clear_all_profiles=True)

    stored = save_table_dataset(
        candidate.name,
        payload.kind,
        df,
        source_path=str(candidate),
    )
    if payload.kind in ("protein", "phospho"):
        clear_uploaded_metadata(payload.kind, clear_all_profiles=True)
    return _table_preview_response(stored)


@router.post("/peptide-path", response_model=PeptidePathResponse)
def set_peptide_path(payload: PeptidePathRequest) -> PeptidePathResponse:
    if not payload.path.strip():
        raise HTTPException(status_code=400, detail="Path must not be empty")

    _resolve_target_package(payload.packageName)
    stored = save_peptide_path(payload.path)
    clear_peptide_metadata(active_package_only=True)
    return _peptide_response(stored)


@router.post("/peptide-file", response_model=PeptidePathResponse)
def upload_peptide_file(
    file: UploadFile = File(...),
    package_name: str | None = Form(default=None, alias="packageName"),
) -> PeptidePathResponse:
    if not file.filename:
        raise HTTPException(status_code=400, detail="Missing filename")
    try:
        ensure_upload_size(file, label="Peptide dataset")
    except ValueError as e:
        raise HTTPException(status_code=413, detail=str(e)) from e

    _resolve_target_package(package_name)

    safe_name = Path(file.filename).name
    target = _peptide_upload_dir() / f"{uuid4().hex}_{safe_name}"

    try:
        with open_private(target, "wb") as handle:
            shutil.copyfileobj(file.file, handle)
    except Exception as e:
        LOGGER.exception("Failed to store peptide file")
        raise HTTPException(status_code=500, detail="Failed to store peptide file.") from e

    stored = save_peptide_path(str(target.resolve()))
    clear_peptide_metadata(active_package_only=True)
    # Keep the displayed dataset filename user-friendly (original selected file name),
    # while path points to the stored absolute temp file.
    stored.filename = safe_name
    return _peptide_response(stored)


