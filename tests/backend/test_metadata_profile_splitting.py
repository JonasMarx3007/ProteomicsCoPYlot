def test_grouping_columns_become_profiles_and_pair_id_stays_structural() -> None:
    metadata = _metadata(
        treatment=["control", "control", "drug", "drug"],
        timepoint=[0, 24, 0, 24],
        sex=["female", "male", "female", "male"],
        pair_id=["subject1", "subject2", "subject1", "subject2"],
    )

    profiles = split_uploaded_metadata_profiles(_data(), metadata)

    assert [name for name, _ in profiles] == ["treatment", "timepoint", "sex"]
    for _, frame in profiles:
        assert frame.columns.tolist() == ["sample", "condition", "pair_id"]
        assert frame["pair_id"].tolist() == metadata["pair_id"].tolist()
    assert profiles[1][1]["condition"].tolist() == ["0", "24", "0", "24"]


def test_normalization_no_longer_builds_subset_or_reverse_columns() -> None:
    metadata = _metadata(
        treatment=["control", "control", "drug", "drug"],
        timepoint=["0h", "24h", "0h", "24h"],
        sex=["female", "male", "female", "male"],
    )

    normalized = normalize_uploaded_metadata(_data(), metadata)

    assert normalized["condition"].tolist() == metadata["treatment"].tolist()
    assert not any("-" in column for column in normalized.columns)
    assert normalized.columns.tolist() == [
        "sample",
        "condition",
        "treatment",
        "timepoint",
        "sex",
    ]


def test_upload_splits_sources_and_generates_each_combination() -> None:
    package = "metadata-split-route"
    create_package(package)
    set_active_package(package)
    save_table_dataset("protein.csv", "protein", _data(), package_name=package)
    metadata = _metadata(
        treatment=["control", "control", "drug", "drug"],
        timepoint=["0h", "24h", "0h", "24h"],
        sex=["female", "male", "female", "male"],
        pair_id=["subject1", "subject2", "subject1", "subject2"],
    )

    with TestClient(app) as client:
        response = _upload(client, metadata)

    assert response.status_code == 200, response.text
    payload = response.json()
    assert payload["profileNames"] == ["treatment", "timepoint", "sex"]
    assert payload["profileName"] == "treatment"
    assert payload["autoGeneratedProfileCount"] == 4
    assert get_active_profile(package_name=package) == "treatment"
    assert set(list_auto_generated_profiles(package_name=package)) == {
        "treatment-timepoint",
        "treatment-sex",
        "timepoint-sex",
        "treatment-timepoint-sex",
    }
    combined = get_uploaded_metadata(
        "protein",
        package_name=package,
        profile_name="treatment-timepoint",
    )
    assert combined is not None and combined.auto_generated
    assert combined.frame["condition"].tolist() == [
        "control-0h",
        "control-24h",
        "drug-0h",
        "drug-24h",
    ]
    assert combined.frame["pair_id"].tolist() == metadata["pair_id"].tolist()

    with TestClient(app) as client:
        selected = client.post(
            "/api/datasets/metadata/profiles/active",
            json={"profileName": "treatment-timepoint"},
        )
    assert selected.status_code == 200, selected.text
    derived_annotation = get_annotation(
        "protein",
        package_name=package,
        metadata_profile_name="treatment-timepoint",
    )
    assert derived_annotation is not None
    assert derived_annotation.metadata["condition"].tolist() == combined.frame[
        "condition"
    ].tolist()


def test_six_grouping_columns_are_rejected_without_partial_profiles() -> None:
    package = "metadata-split-too-many"
    create_package(package)
    set_active_package(package)
    save_table_dataset("protein.csv", "protein", _data(), package_name=package)
    metadata = _metadata(
        group1=["a"] * 4,
        group2=["b"] * 4,
        group3=["c"] * 4,
        group4=["d"] * 4,
        group5=["e"] * 4,
        group6=["f"] * 4,
    )

    with TestClient(app) as client:
        response = _upload(client, metadata)

    assert response.status_code == 400
    assert "At most 5" in response.json()["detail"]
    assert list_profiles(package_name=package) == ["Metadata"]
    assert list_auto_generated_profiles(package_name=package) == []


def test_two_column_metadata_keeps_the_selected_profile() -> None:
    package = "metadata-split-backward-compatible"
    create_package(package)
    set_active_package(package)
    save_table_dataset("protein.csv", "protein", _data(), package_name=package)
    create_profile("Experiment", package_name=package)
    set_active_profile("Experiment", package_name=package)
    metadata = _metadata(condition=["control", "control", "drug", "drug"])

    with TestClient(app) as client:
        response = _upload(client, metadata)

    assert response.status_code == 200, response.text
    assert response.json()["profileNames"] == ["Experiment"]
    assert get_active_profile(package_name=package) == "Experiment"
    stored = get_uploaded_metadata(
        "protein",
        package_name=package,
        profile_name="Experiment",
    )
    assert stored is not None
    assert stored.frame.columns.tolist() == ["sample", "condition"]
