SAMPLES = ["sample1", "sample2", "sample3", "sample4"]


def _data() -> pd.DataFrame:
    rows = 50
    return pd.DataFrame(
        {
            "ProteinNames": [f"P{row}" for row in range(rows)],
            **{
                sample: [20.0 + index + row / 100 for row in range(rows)]
                for index, sample in enumerate(SAMPLES)
            },
        }
    )


def _metadata(**extra_columns: list[object]) -> pd.DataFrame:
    return pd.DataFrame({"sample": SAMPLES, **extra_columns})


def _upload(client: TestClient, metadata: pd.DataFrame):
    return client.post(
        "/api/annotations/metadata/upload",
        data={"kind": "protein"},
        files={
            "file": (
                "metadata.csv",
                io.BytesIO(metadata.to_csv(index=False).encode("utf-8")),
                "text/csv",
            )
        },
    )


